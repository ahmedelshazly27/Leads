export function contentsChapter(c: ReportCtx, chapters: Chapter[]): Chapter {
  const rows: { key: string; cells: ReactNode[] }[] = [];
  let n = 0;
  for (const ch of chapters) {
    if (ch.inToc === false) continue;
    n++;
    rows.push({
      key: ch.id,
      cells: [
        <span className="rp-toc-n">{String(n).padStart(2, "0")}</span>,
        <b className="rp-toc-ch">{ch.title}</b>,
        <span className="rp-toc-p">{c.pageNo(ch.id)}</span>,
      ],
    });
    const subs: { key: string; title: string }[] = [];
    for (const b of ch.blocks) {
      if (b.toc) subs.push({ key: b.key, title: b.toc });
      if (b.kind === "table") for (const r of b.rows) if (r.toc) subs.push({ key: r.key, title: r.toc });
    }
    for (const s of subs)
      rows.push({
        key: `${ch.id}/${s.key}`,
        cells: ["", <span className="rp-toc-sub">{s.title}</span>, <span className="rp-toc-p">{c.pageNo(tocId(ch.id, s.key))}</span>],
      });
  }
  return {
    id: "contents",
    title: "Contents",
    inToc: false,
    blocks: [title("Contents"), table("toc", [["", "7%"], ["Section", "81%"], ["Page", "12%"]], rows, { className: "rp-toc" })],
  };
}

